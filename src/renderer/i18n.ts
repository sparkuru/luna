export function formatMoney(
  locale: AppLocale,
  value: string,
  currency: string,
  precision: number,
): string {
  const amount = parseMinorUnits(value);
  const negative = amount < 0n;
  const magnitude = negative ? -amount : amount;
  const scale = 10n ** BigInt(precision);
  const whole = magnitude / scale;
  const fraction = precision === 0 ? '' : (magnitude % scale).toString().padStart(precision, '0');
  const formatter = new Intl.NumberFormat(locale, {
    style: 'currency',
    currency,
    minimumFractionDigits: precision,
    maximumFractionDigits: precision,
  });
  const sample = negative ? -(whole === 0n ? 1n : whole) : whole;
  const wholeParts = new Intl.NumberFormat(locale, { maximumFractionDigits: 0 }).formatToParts(whole);
  const parts = formatter.formatToParts(sample);
  const firstInteger = parts.findIndex((part) => part.type === 'integer');
  let lastInteger = -1;
  for (let index = parts.length - 1; index >= 0; index -= 1) {
    const part = parts[index];
    if (part?.type === 'integer' || part?.type === 'group') {
      lastInteger = index;
      break;
    }
  }
  const result = [...parts];
  if (firstInteger >= 0 && lastInteger >= firstInteger) {
    result.splice(firstInteger, lastInteger - firstInteger + 1, ...wholeParts);
  }
  for (const part of result) {
    if (part.type === 'fraction') part.value = fraction;
  }
  return result.map((part) => part.value).join('');
}

export function formatMonth(locale: AppLocale, month: string): string {
  const [year, monthNumber] = month.split('-');
  const date = new Date(Date.UTC(Number(year), Number(monthNumber) - 1, 1));
  return new Intl.DateTimeFormat(locale, { month: 'long', year: 'numeric', timeZone: 'UTC' }).format(date);
}

export function formatDate(locale: AppLocale, value: string): string {
  const [year, month, day] = value.split('-');
  const date = new Date(Date.UTC(Number(year), Number(month) - 1, Number(day), 12));
  return new Intl.DateTimeFormat(locale, { month: 'short', day: 'numeric', year: 'numeric', timeZone: 'UTC' }).format(date);
}
